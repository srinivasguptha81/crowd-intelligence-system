"""
Train a supervised temporal crowd-risk forecasting model from labeled feature windows.

Supports both:
  1. Legacy 3-feature CSV (`density_signal`, `motion_signal`, `surge_signal`)
  2. Full 15-feature spatio-temporal schema generated by `extract_features.py`

Label (`event_within_horizon`) must be 1 only when a clearly defined, annotated
adverse crowd event begins within the chosen forecast horizon (0 otherwise).
Always split by `video_id` so overlapping frames never leak across train/test splits.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path

import joblib
import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier, VotingClassifier
from sklearn.impute import SimpleImputer
from sklearn.metrics import average_precision_score, classification_report, confusion_matrix
from sklearn.model_selection import GroupShuffleSplit, train_test_split
from sklearn.pipeline import Pipeline

LEGACY_FEATURES = ["density_signal", "motion_signal", "surge_signal"]
TEMPORAL_FEATURES = [
    "density_signal",
    "motion_signal",
    "surge_signal",
    "peak_density_p_m2",
    "flow_entropy",
    "counter_flow",
    "positive_divergence",
    "negative_divergence",
    "crowd_pressure",
    "crush_stagnation_signal",
    "panic_score_norm",
    "density_slope",
    "pressure_slope",
    "panic_rolling_mean",
    "pressure_rolling_max",
]
TARGET = "event_within_horizon"


def _load_csv(csv_path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with csv_path.open("r", encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            raise SystemExit("CSV file has no header row.")
        rows = list(reader)
        return list(reader.fieldnames), rows


def main() -> None:
    parser = argparse.ArgumentParser(description="Train CrowdGuard temporal risk forecasting model.")
    parser.add_argument("--csv", required=True, help="Labeled CSV path")
    parser.add_argument("--out", default="models/crowd_risk_model.joblib", help="Output model bundle path")
    parser.add_argument(
        "--group-col",
        default="video_id",
        help="Group column to keep source videos separate across train/test splits",
    )
    args = parser.parse_args()

    fieldnames, raw_rows = _load_csv(Path(args.csv))
    if TARGET not in fieldnames:
        raise SystemExit(f"Missing required target column '{TARGET}'.")

    available_temporal = [c for c in TEMPORAL_FEATURES if c in fieldnames]
    if len(available_temporal) >= 6:
        features = available_temporal
    elif all(c in fieldnames for c in LEGACY_FEATURES):
        features = LEGACY_FEATURES
    else:
        raise SystemExit(
            f"CSV must contain at least {LEGACY_FEATURES} or a subset of {TEMPORAL_FEATURES}."
        )

    X_list: list[list[float]] = []
    y_list: list[int] = []
    groups: list[str] = []

    for row in raw_rows:
        target_raw = (row.get(TARGET) or "").strip()
        if target_raw == "":
            continue
        try:
            y_val = int(float(target_raw))
        except ValueError:
            continue
        vec: list[float] = []
        for col in features:
            raw_val = (row.get(col) or "").strip()
            try:
                vec.append(float(raw_val) if raw_val != "" else float("nan"))
            except ValueError:
                vec.append(float("nan"))
        X_list.append(vec)
        y_list.append(y_val)
        groups.append((row.get(args.group_col) or "default").strip() if args.group_col else "default")

    if not X_list:
        raise SystemExit("No valid labeled rows found in CSV.")

    X = np.asarray(X_list, dtype=float)
    y = np.asarray(y_list, dtype=int)
    if set(np.unique(y).tolist()) != {0, 1}:
        raise SystemExit("Training requires both binary label classes 0 and 1.")

    unique_groups = set(groups)
    if args.group_col and args.group_col in fieldnames and len(unique_groups) >= 2:
        splitter = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=42)
        train_idx, test_idx = next(splitter.split(X, y, groups=np.asarray(groups)))
    else:
        print("WARNING: fewer than 2 video groups present; falling back to stratified split.")
        train_idx, test_idx = train_test_split(
            np.arange(len(y)), test_size=0.25, random_state=42, stratify=y
        )

    X_train, X_test = X[train_idx], X[test_idx]
    y_train, y_test = y[train_idx], y[test_idx]

    rf = RandomForestClassifier(
        n_estimators=250,
        min_samples_leaf=3,
        class_weight="balanced",
        random_state=42,
    )
    hgb = HistGradientBoostingClassifier(
        max_iter=180,
        max_depth=5,
        learning_rate=0.06,
        class_weight="balanced",
        random_state=42,
    )
    ensemble = VotingClassifier(
        estimators=[("rf", rf), ("hgb", hgb)],
        voting="soft",
    )
    pipeline = Pipeline([("imputer", SimpleImputer(strategy="median")), ("classifier", ensemble)])
    pipeline.fit(X_train, y_train)

    pred = pipeline.predict(X_test)
    proba = pipeline.predict_proba(X_test)[:, 1]
    print(f"Trained temporal ensemble over {len(features)} features: {features}")
    print(classification_report(y_test, pred, zero_division=0))
    print("Confusion matrix:\n", confusion_matrix(y_test, pred))
    try:
        print("Average precision (PR-AUC):", round(float(average_precision_score(y_test, proba)), 4))
    except Exception:
        pass

    bundle = {
        "model": pipeline,
        "features": features,
        "arch": "rf_histgb_ensemble",
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(bundle, out)
    print(f"Saved model bundle to {out.resolve()}")
    print("Only deploy if labels reflect verified real-venue ground truth split by source video.")


if __name__ == "__main__":
    main()
